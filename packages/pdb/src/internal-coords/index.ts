/**
 * @packageDocumentation
 * Internal coordinates: a protein described by its bond lengths, bond angles and dihedral angles rather than by
 * Cartesian coordinates (Biopython's `Bio.PDB.internal_coords`).
 *
 * `AtomKey` is the keystone: it names an atom across a chain, disorder included, and its ordering is what puts a
 * residue's hedra and dihedra in a canonical sequence. The geometry rests on `../homog.ts`, ported with
 * `Bio.PDB.vectors`. Measuring a chain's angles from its atoms is here; assembling atoms from the angles is not
 * yet.
 *
 * - `ic-data.ts`: the tables from `Bio.PDB.ic_data` (generated by `reference/gen_data.py`)
 * - `atom-key.ts`: `AtomKey`, with `FIELDS` and `FIELD_NAMES`
 * - `settings.ts`: `icSettings`, the class-level switches Biopython keeps on `IC_Residue`
 * - `ic-chain.ts`: `IC_Chain` — the registries a residue's angles are kept in, the chain's atom and value
 *   arrays, and the measurement that fills them
 * - `ic-measure.ts`: the measurement itself — the value arrays, the index maps and the angles
 * - `ic-residue.ts`: `IC_Residue` — which atoms a residue keeps and the keys it keeps them under
 * - `edron.ts`: `Edron`, `Hedron` and `Dihedron` — the angles themselves. Their lengths and angle values live on
 *   the chain, so a di/hedron with no chain reads 0 for them (360 for a dihedral angle).
 */

