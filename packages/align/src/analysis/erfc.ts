/** Zero out the low 32 bits of a double (fdlibm's `SET_LOW_WORD(z, 0)`). */
function truncLow(x: number): number {
  const buf = new DataView(new ArrayBuffer(8));
  buf.setFloat64(0, x);
  buf.setUint32(4, 0);
  return buf.getFloat64(0);
}

/**
 * `math.erfc(x)`: 1 - erf(x), accurate in the tail.
 *
 * @param x - The argument.
 */
export function erfc(x: number): number {
  if (Number.isNaN(x)) return NaN;
  if (x === Infinity) return 0;
  if (x === -Infinity) return 2;
  const ax = Math.abs(x);
  if (ax < 0.84375) {
    if (ax < 2 ** -56) return 1 - x;
    const z = x * x;
    const r = pp[0]! + z * (pp[1]! + z * (pp[2]! + z * (pp[3]! + z * pp[4]!)));
    const s = 1 + z * (qq[0]! + z * (qq[1]! + z * (qq[2]! + z * (qq[3]! + z * qq[4]!))));
    const y = r / s;
    if (x < 0.25) return 1 - (x + x * y);
    return 0.5 - (x - 0.5 + x * y);
  }
  if (ax < 1.25) {
    const s = ax - 1;
    const P = pa[0]! + s * (pa[1]! + s * (pa[2]! + s * (pa[3]! + s * (pa[4]! + s * (pa[5]! + s * pa[6]!)))));
    const Q = 1 + s * (qa[0]! + s * (qa[1]! + s * (qa[2]! + s * (qa[3]! + s * (qa[4]! + s * qa[5]!)))));
    return x >= 0 ? 1 - erx - P / Q : 1 + (erx + P / Q);
  }
  if (ax < 28) {
    const s = 1 / (ax * ax);
    let R: number, S: number;
    if (ax < 1 / 0.35) {
      R = ra[0]! + s * (ra[1]! + s * (ra[2]! + s * (ra[3]! + s * (ra[4]! + s * (ra[5]! + s * (ra[6]! + s * ra[7]!))))));
      S = 1 + s * (sa[0]! + s * (sa[1]! + s * (sa[2]! + s * (sa[3]! + s * (sa[4]! + s * (sa[5]! + s * (sa[6]! + s * sa[7]!)))))));
    } else {
      if (x < -6) return 2;
      R = rb[0]! + s * (rb[1]! + s * (rb[2]! + s * (rb[3]! + s * (rb[4]! + s * (rb[5]! + s * rb[6]!)))));
      S = 1 + s * (sb[0]! + s * (sb[1]! + s * (sb[2]! + s * (sb[3]! + s * (sb[4]! + s * (sb[5]! + s * sb[6]!))))));
    }
    const z = truncLow(ax);
    const r = Math.exp(-z * z - 0.5625) * Math.exp((z - ax) * (z + ax) + R / S);
    return x > 0 ? r / ax : 2 - r / ax;
  }
  return x > 0 ? 0 : 2;
}
