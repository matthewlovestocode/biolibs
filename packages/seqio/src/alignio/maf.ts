/** Multiple Alignment Format (`maf`, as used by UCSC and Galaxy). */

import { AssertionError, ValueError, pyInt, pyStr, pyStrip, pySplit } from "@biolibs/core";
import { MultipleSeqAlignment } from "@biolibs/align";
import { Seq } from "@biolibs/seq";
import { SeqRecord } from "@biolibs/seqrecord";
import type { LineStream } from "../handles.js";
import { AlignmentIterator, SequentialAlignmentWriter } from "./interfaces.js";

/** Python `'%15s' % value`: right-aligned text. */
const right = (value: unknown, width: number): string => pyStr(value).padStart(width, " ");

/** Writes MAF blocks (`a` line, then one `s` line per sequence). */
export class MafWriter extends SequentialAlignmentWriter {
  writeHeader(): void {
    this.handle.write("##maf version=1 scoring=none\n");
    this.handle.write("# generated by Biopython\n\n");
  }

  private writeRecord(record: SeqRecord): void {
    const a = record.annotations;
    const strand = a.get("strand") === 1 ? "+" : a.get("strand") === -1 ? "-" : "+";
    const text = record.seq!.toString();
    const fields = [
      "s",
      (record.id as string).replaceAll(" ", "_").padEnd(40, " "),
      right(a.has("start") ? a.get("start") : 0, 15),
      right(a.has("size") ? a.get("size") : text.replaceAll("-", "").length, 5),
      strand,
      right(a.has("srcSize") ? a.get("srcSize") : 0, 15),
      text,
    ];
    this.handle.write(`${fields.join(" ")}\n`);
  }

  writeAlignment(alignment: MultipleSeqAlignment): void {
    if (!(alignment instanceof MultipleSeqAlignment)) throw new TypeError("Expected an alignment object");
    if (new Set([...alignment].map((x) => x.length)).size > 1) throw new ValueError("Sequences must all be the same length");
    const stored = alignment["_annotations"];
    const anno = stored instanceof Map ? [...stored].filter(([x]) => x === "score" || x === "pass").map(([x, y]) => `${x}=${pyStr(y)}`).join(" ") : "score=0.00";
    this.handle.write(`a ${anno}\n`);
    for (const record of alignment) this.writeRecord(record);
    this.handle.write("\n");
  }
}

/** Generator over the alignment blocks of a MAF file. */
function* mafBlocks(handle: LineStream, seqCount: number | null): Generator<MultipleSeqAlignment> {
  let inABundle = false;
  let annotations = new Map<string, string>();
  let records: SeqRecord[] = [];
  for (;;) {
    const line = handle.readline();
    if (inABundle) {
      if (line.startsWith("s")) {
        const split = pySplit(pyStrip(line));
        if (split.length !== 7) throw new ValueError("Error parsing alignment - 's' line must have 7 fields");
        const strand = split[4] === "+" ? 1 : split[4] === "-" ? -1 : 1;
        const anno = new Map<string, unknown>([["start", pyInt(split[2]!)], ["size", pyInt(split[3]!)], ["strand", strand], ["srcSize", pyInt(split[5]!)]]);
        let sequence = split[6]!;
        if (sequence.includes(".")) {
          if (records.length === 0) throw new ValueError("Found dot/period in first sequence of alignment");
          const ref = records[0]!.seq!.toString();
          // `zip` stops at the shorter of the two.
          const n = Math.min(sequence.length, ref.length);
          let out = "";
          for (let i = 0; i < n; i++) out += sequence[i] === "." ? ref[i] : sequence[i];
          sequence = out;
        }
        records.push(new SeqRecord(new Seq(sequence), split[1]!, split[1]!, "", null, null, anno));
      } else if (line.startsWith("i") || line.startsWith("e") || line.startsWith("q") || line.startsWith("#")) {
        // information, empty-region, quality and comment lines are not kept
      } else if (!pyStrip(line)) {
        if (seqCount !== null && records.length !== seqCount) throw new AssertionError();
        const alignment = new MultipleSeqAlignment(records);
        alignment["_annotations"] = annotations;
        yield alignment;
        inABundle = false;
        annotations = new Map();
        records = [];
      } else {
        throw new ValueError(`Error parsing alignment - unexpected line:\n${line}`);
      }
    } else if (line.startsWith("a")) {
      inABundle = true;
      const annotStrings = pySplit(pyStrip(line)).slice(1);
      if (annotStrings.length !== line.split("=").length - 1) throw new ValueError("Error parsing alignment - invalid key in 'a' line");
      annotations = new Map();
      annotStrings.forEach((s, i) => {
        const pair = s.split("=");
        if (pair.length !== 2) throw new ValueError(`dictionary update sequence element #${i} has length ${pair.length}; 2 is required`);
        annotations.set(pair[0]!, pair[1]!);
      });
    } else if (line.startsWith("#")) {
      // comment
    } else if (!line) {
      break;
    }
  }
}

/** Reads MAF alignment blocks; dots in later sequences are replaced by the first sequence's letters. */
export class MafIterator extends AlignmentIterator {
  private readonly blocks: Generator<MultipleSeqAlignment>;

  constructor(handle: LineStream, seqCount: number | null = null) {
    super(handle, seqCount);
    this.blocks = mafBlocks(handle, seqCount);
  }

  nextAlignment(): MultipleSeqAlignment | null {
    const next = this.blocks.next();
    return next.done ? null : next.value;
  }
}
