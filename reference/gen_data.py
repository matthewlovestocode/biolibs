lines = [HDR, "/**\n * Constants from Biopython's `Bio.Data.IUPACData`. Names are the camelCase of the Python names.\n */\n\n"]
names = []
for n in sorted(x for x in dir(IUPACData) if not x.startswith("_")):
    v = getattr(IUPACData, n)
    if callable(v) or type(v).__name__ == "module": continue
    names.append(n)
    if n not in DESCRIPTIONS:
        raise SystemExit(f"IUPACData.{n} has no entry in DESCRIPTIONS (gen_data.py); describe it before regenerating")
    lines.append(f"/** {DESCRIPTIONS[n]} */\nexport const {camel(n)}: {ts_type(v)} = {js(v)};\n\n")
open(os.path.join(OUT, "iupac-data.ts"), "w").write("".join(lines))
print("iupac constants:", len(names))

# NCBI tables: exactly the args passed to register_ncbi_table.
tables = []
for tid in sorted(CodonTable.unambiguous_dna_by_id):
    t = CodonTable.unambiguous_dna_by_id[tid]
    # names = split names + [alt_name]; last entry is the alt name (may be None)
    tables.append({
        "id": tid, "names": t.names, "table": t.forward_table,
        "startCodons": t.start_codons, "stopCodons": t.stop_codons,
    })
