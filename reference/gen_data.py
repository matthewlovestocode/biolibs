def camel(s):
    parts = s.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])

def ts_type(v):
    if isinstance(v, str): return "string"
    if isinstance(v, (int, float)): return "number"
    if isinstance(v, tuple):  return "[" + ", ".join(ts_type(x) for x in v) + "]"
    if isinstance(v, dict):
        vals = {ts_type(x) for x in v.values()}
        return "Record<string, " + (vals.pop() if len(vals) == 1 else " | ".join(sorted(vals))) + ">"
    raise TypeError(type(v))

def js(v):
    if isinstance(v, tuple): v = list(v)
    return json.dumps(v if not isinstance(v, dict) else {k: (list(x) if isinstance(x, tuple) else x) for k, x in v.items()}, indent=2)


