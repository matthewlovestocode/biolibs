"""Generate packages/align/src/pairwise/gap-properties.ts from Biopython's C pairwise aligner.

The ~50 gap-score properties of PairwiseAligner follow a regular pattern (which of the twelve base scores
they read and write, whether a gap function is involved). Rather than copy them by hand, read the pattern
from Bio/Align/_pairwisealigner.c and the renamed-attribute table from Bio/Align/__init__.py.
Do not edit the generated file by hand.
"""
import os, re
import Bio
from Bio import Align
import Bio.Align as A

OUT = os.path.join(os.path.dirname(__file__), "..", "packages", "align", "src", "pairwise", "gap-properties.ts")
C = open(os.path.join(os.path.dirname(A.__file__), "_pairwisealigner.c")).read()

def camel(s):
    p = s.split("_")
    return p[0] + "".join(x.capitalize() for x in p[1:])

def body(name):
    i = C.index(name + "(Aligner")
    return C[i:C.index("\n}\n", i)]

props = []
for pub, g, s in re.findall(r"\{\"(\w+)\",\s*\n\s*\(getter\)Aligner_get_(\w+),\s*\n\s*\(setter\)(\w+)", C):
    if pub in ("mode", "match_score", "mismatch_score", "match", "mismatch", "substitution_matrix", "epsilon", "wildcard", "algorithm"): continue
    gb, sb = body("Aligner_get_" + g), body("Aligner_set_" + g)
    fields = sorted(set(re.findall(r"self->((?:open|extend)_\w+_score)\b", gb)), key=lambda f: re.findall(r"self->((?:open|extend)_\w+_score)\b", gb).index(f))
    assert sorted(fields) == sorted(set(re.findall(r"self->((?:open|extend)_\w+_score)\s*=\s*score", sb))), pub
    ins, dele = "insertion_score_function" in gb, "deletion_score_function" in gb
    side = "both" if ins and dele else "insertion" if ins else "deletion"
    callable_ = "PyCallable_Check" in sb
    doc = re.search(r'Aligner_%s__doc__\[\]\s*=\s*"([^"]*)"' % pub, C).group(1)
    props.append((pub, fields, side, callable_, doc))

renames = Align.PairwiseAligner._new_keys

lines = [f"// GENERATED by reference/gen_aligner_props.py from Biopython {Bio.__version__}. DO NOT EDIT BY HAND.\n\n",
         "/**\n * The gap-score properties of `PairwiseAligner`, read from Biopython's C implementation: for each property, the\n * base scores it covers and how it treats gap functions.\n */\n\n",
         "/** A gap score function: given a position and a gap length it returns the score of that gap (Biopython passes `(i, length)`). */\nexport type GapScoreFunction = (position: number, length: number) => number;\n\n",
         "/** How one gap-score property reads and writes the twelve base scores. */\nexport interface GapPropertySpec {\n  /** The Python name, e.g. `open_internal_gap_score`. */\n  name: string;\n  /** The base scores (camelCase field names) it covers, in the order the C getter compares them. */\n  fields: string[];\n  /** Which gap functions a function-valued setting affects: insertions, deletions or both. */\n  side: \"both\" | \"insertion\" | \"deletion\";\n  /** Whether the property may hold a gap function (only `gap_score`, `insertion_score` and `deletion_score`). */\n  callable: boolean;\n  /** One-line description from Biopython. */\n  doc: string;\n}\n\n",
         "/** Every gap-score property of Biopython's aligner, in Biopython's order. */\nexport const GAP_PROPERTIES: GapPropertySpec[] = [\n"]
for pub, fields, side, cal, doc in props:
    lines.append(f'  {{ name: "{pub}", fields: [{", ".join(chr(34) + camel(f) + chr(34) for f in fields)}], side: "{side}", callable: {str(cal).lower()}, doc: "{doc}" }},\n')
lines.append("];\n\n")
lines.append("/** Attributes Biopython renamed (old Python name to new), which still work but emit a `BiopythonDeprecationWarning`. */\nexport const RENAMED_PROPERTIES: Record<string, string> = {\n")
for k, v in renames.items(): lines.append(f'  "{k}": "{v}",\n')
lines.append("};\n\n")
lines.append("/** Typed accessors for the gap-score properties (installed on `PairwiseAligner` from {@link GAP_PROPERTIES}). */\nexport interface GapScoreAccessors {\n")
for pub, fields, side, cal, doc in props:
    t = "number | GapScoreFunction" if cal else "number"
    lines.append(f"  /** {doc} */\n  {camel(pub)}: {t};\n")
for old in renames:
    lines.append(f"  /** Deprecated name of `{camel(renames[old])}`. */\n  {camel(old)}: {'number | GapScoreFunction' if 'function' in old else 'number'};\n")
lines.append("}\n")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("".join(lines))
print(len(props), "gap properties,", len(renames), "renamed")
