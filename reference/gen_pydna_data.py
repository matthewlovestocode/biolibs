"""Generate packages/dseq/src/data/dscode.ts from pydna's alphabet. Never edit that file by hand.

pydna 5 stores a double-stranded sequence as one letter per base pair: `G` is G over C, `P` is a G with
nothing opposite it, `Q` is a C on the lower strand alone, and so on through RNA, the ambiguity codes,
loops and mismatches. Everything `Dseq` does is a translation or a regular expression over that string,
so these tables are the whole foundation and they are copied from the reference rather than retyped.
"""
import json, os
import pydna
import pydna.alphabet as a

OUT = os.path.join(os.path.dirname(__file__), "..", "packages", "dseq", "src", "data", "dscode.ts")

#: Every export needs a sentence, as `gen_data.py` requires for the generated Biopython data.
DESCRIPTIONS = {
    "PYDNA_VERSION": "The pydna release these tables were taken from.",
    "BASEPAIR_TO_CODE": "The code letter for a `watson + crick` pair, including the mixed-case spellings.",
    "CODE_GROUPS": "Which kind of position each code letter stands for, under pydna's own group names.",
    "TO_WATSON": "Translation table from a code letter to the upper strand's base, or a space where it has none.",
    "TO_CRICK": "Translation table from a code letter to the lower strand's base, or a space where it has none.",
    "TO_FULL": "Translation table from a code letter to the base of the blunt, fully double-stranded reading.",
    "COMPLEMENT": "Translation table that swaps the two strands of a code letter.",
    "DS_LETTERS": "The code letters whose position is double stranded.",
    "FIVE_PRIME_SS_LETTERS": "The code letters that are a base on the upper strand alone.",
    "THREE_PRIME_SS_LETTERS": "The code letters that are a base on the lower strand alone.",
    "GAP": "The code letter for a position with nothing on either strand.",
}


def table(bytes_table):
    """@returns A 256-character string where position `i` is what byte `i` translates to."""
    return bytes_table.decode("latin-1")


values = {
    "PYDNA_VERSION": pydna.__version__,
    "BASEPAIR_TO_CODE": {w + c: code for (w, c), code in a.basepair_dict.items()},
    "CODE_GROUPS": {group: "".join(sorted(set(pairs.values()))) for group, pairs in a.codes.items()},
    "TO_WATSON": table(a.dscode_to_watson_table),
    "TO_CRICK": table(a.dscode_to_crick_table),
    "TO_FULL": table(a.dscode_to_full_sequence_table),
    "COMPLEMENT": table(a.complement_table_for_dscode),
    "DS_LETTERS": a.ds_letters,
    "FIVE_PRIME_SS_LETTERS": a.five_prime_ss_letters,
    "THREE_PRIME_SS_LETTERS": a.three_prime_ss_letters,
    "GAP": a.emptyspace if isinstance(getattr(a, "emptyspace", None), str) else " ",
}

missing = [k for k in values if k not in DESCRIPTIONS]
if missing:
    raise SystemExit(f"add a DESCRIPTIONS entry for {missing}")

lines = [
    "/**",
    " * pydna's dscode alphabet: one letter per base pair.",
    " *",
    " * Generated by `reference/gen_pydna_data.py` from pydna " + pydna.__version__ + ". Do not edit by hand.",
    " */",
    "",
]
for name, value in values.items():
    lines.append(f"/** {DESCRIPTIONS[name]} */")
    if isinstance(value, str):
        lines.append(f"export const {name} = {json.dumps(value)};")
    elif name == "BASEPAIR_TO_CODE":
        entries = ", ".join(f"[{json.dumps(k)}, {json.dumps(v)}]" for k, v in sorted(value.items()))
        lines.append(f"export const {name}: ReadonlyMap<string, string> = new Map([{entries}]);")
    else:
        entries = ", ".join(f"[{json.dumps(k)}, {json.dumps(v)}]" for k, v in value.items())
        lines.append(f"export const {name}: ReadonlyMap<string, string> = new Map([{entries}]);")
    lines.append("")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines))
print(f"{len(values)} tables -> {os.path.relpath(OUT)}")
