"""Generate packages/dseq/src/data/codon.ts from pydna.codon. Never edit that file by hand.

`pydna.codon` holds the per-organism numbers that `pydna.seq.Seq`'s expression methods read: how often each
codon is the preferred one for its amino acid, which codons are rare enough to slow translation down, how
strong a start and a stop codon are, and how long a protein lasts given its second residue (the N-end rule).
They are published measurements rather than anything pydna computes, so they are copied from the reference.

Two things the tables do not agree on are worth keeping in view, because they decide what raises. Only
`sce` has codon weights, while `rare_codons`, `start`, `stop` and `n_end` have `sce` and `eco`; and the
`eco` start table does not list `ATG`, so `startcodon("eco")` is None for an ordinary gene.
"""
import json, os
import pydna
import pydna.codon as c

OUT = os.path.join(os.path.dirname(__file__), "..", "packages", "dseq", "src", "data", "codon.ts")

#: Every export needs a sentence, as `gen_data.py` requires for the generated Biopython data.
DESCRIPTIONS = {
    "CODON_PYDNA_VERSION": "The pydna release these codon tables were taken from.",
    "CODON_WEIGHTS": "Each codon's weight for the codon adaptation index, by organism; only `sce` has any.",
    "RARE_CODONS": "The codons counted as rare, by organism, in the order pydna lists them.",
    "START_CODONS": "How strong each start codon is, by organism.",
    "STOP_CODONS": "How strong each stop codon is, by organism.",
    "N_END": "How long a protein lasts given its second residue's three-letter name, by organism.",
}

values = {
    "CODON_PYDNA_VERSION": pydna.__version__,
    "CODON_WEIGHTS": {org: dict(sorted(w.items())) for org, w in sorted(c.weights.items())},
    # Order is kept: `express` lays one column out per rare codon, in this order.
    "RARE_CODONS": {org: list(codons) for org, codons in sorted(c.rare_codons.items())},
    "START_CODONS": {org: dict(sorted(w.items())) for org, w in sorted(c.start.items())},
    "STOP_CODONS": {org: dict(sorted(w.items())) for org, w in sorted(c.stop.items())},
    "N_END": {org: dict(sorted(w.items())) for org, w in sorted(c.n_end.items())},
}

missing = [k for k in values if k not in DESCRIPTIONS]
if missing:
    raise SystemExit(f"add a DESCRIPTIONS entry for {missing}")


def nested(value):
    """@param value - A dict of per-organism dicts. @returns It as a TypeScript nested Map literal."""
    orgs = []
    for org, inner in value.items():
        if isinstance(inner, list):
            orgs.append(f"[{json.dumps(org)}, {json.dumps(inner)}]")
        else:
            entries = ", ".join(f"[{json.dumps(k)}, {json.dumps(v)}]" for k, v in inner.items())
            orgs.append(f"[{json.dumps(org)}, new Map([{entries}])]")
    return ", ".join(orgs)


lines = [
    "/**",
    " * pydna's per-organism codon tables: usage weights, the rare codons, start and stop strengths, and the",
    " * N-end rule's half-lives.",
    " *",
    " * Generated by `reference/gen_pydna_codon_data.py` from pydna " + pydna.__version__ + ". Do not edit by hand.",
    " */",
    "",
]
for name, value in values.items():
    lines.append(f"/** {DESCRIPTIONS[name]} */")
    if isinstance(value, str):
        lines.append(f"export const {name} = {json.dumps(value)};")
    elif name == "RARE_CODONS":
        lines.append(f"export const {name}: ReadonlyMap<string, readonly string[]> = "
                     f"new Map([{nested(value)}]);")
    elif name == "N_END":
        lines.append(f"export const {name}: ReadonlyMap<string, ReadonlyMap<string, string>> = "
                     f"new Map([{nested(value)}]);")
    else:
        lines.append(f"export const {name}: ReadonlyMap<string, ReadonlyMap<string, number>> = "
                     f"new Map([{nested(value)}]);")
    lines.append("")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines))
print(f"{len(values)} codon tables -> {os.path.relpath(OUT)}")
